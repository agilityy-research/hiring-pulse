#!/usr/bin/env python3
"""Writes the stub pages that Jekyll turns into one page per (function, US city) salary cell, per city and per top skill,
reading _data/markets.json. Each stub is front matter plus one include; the figures come from the data file at build
time, so the stubs only need regenerating when a new city, function or skill appears (run after a markets refresh adds
one). Stubs the data no longer backs are removed. Standard library only:

    python3 scripts/make_subpages.py            # from the repository root
"""
import json
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARK = "<!-- generated by scripts/make_subpages.py -->"


def slug(s: str) -> str:
    """Jekyll's slugify in 'latin' mode: accents stripped, anything but letters and digits becomes one hyphen."""
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", s.lower())).strip("-")


def yaml(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def write(path: Path, front: dict, include: str, written: set) -> None:
    lines = ["---"] + [f"{k}: {yaml(v) if isinstance(v, str) else v}" for k, v in front.items()] + ["---", MARK, include, ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))
    written.add(path)


def main() -> None:
    m = json.loads((ROOT / "_data" / "markets.json").read_text())
    written: set = set()
    usd = next((t for t in m["pay"]["tables"] if t["key"] == "usd-year"), None)
    if usd and usd.get("cityFunction"):
        fns = usd["cityFunction"]["functions"]
        for row in usd["cityFunction"]["rows"]:
            for fn, cell in zip(fns, row["cells"]):
                if not cell or not cell.get("median"):
                    continue
                city = row["city"]
                write(ROOT / "data" / "salaries" / f"{slug(fn)}-{slug(city)}.html", {
                    "title": f"{fn} salaries in {city}: what startups offer in their job postings",
                    "description": f"The median salary US startups advertise for {fn} roles in {city}, against the function across US cities and the city across functions, with the number of postings behind each figure and {fn} pay by level. Updated weekly.",
                    "permalink": f"/data/salaries/{slug(fn)}-{slug(city)}/", "layout": "default", "bands": "true",
                    "jsonld": "dataset", "dataset_name": f"Startup {fn} salaries in {city}", "fn": fn, "city": city},
                    "{% include salary-pair.html fn=page.fn city=page.city %}", written)
    for c in m.get("cities", []):
        city = c["label"]
        write(ROOT / "data" / "cities" / f"{slug(city)}.html", {
            "title": f"Startup hiring in {city}: open roles, work mode and pay",
            "description": f"Startups and scale-ups hiring in {city} this week: open roles and companies, the functions they hire for, the remote, hybrid and on-site split, roles opened in the last week and advertised pay. Counted daily from their own job boards.",
            "permalink": f"/data/cities/{slug(city)}/", "layout": "default", "bands": "true",
            "jsonld": "dataset", "dataset_name": f"Startup hiring in {city}", "city": city},
            "{% include city-page.html city=page.city %}", written)
    if m.get("skills", {}).get("ready"):
        for k in m["skills"]["top"]:
            name = k["name"]
            write(ROOT / "data" / "skills" / f"{slug(name)}.html", {
                "title": f"{name} in startup job descriptions: how many roles ask for it, by function",
                "description": f"The share of startup job descriptions that name {name}, overall and by function, from a daily read of 21,000+ company job boards. Updated weekly.",
                "permalink": f"/data/skills/{slug(name)}/", "layout": "default", "bands": "true",
                "jsonld": "dataset", "dataset_name": f"{name} in startup job descriptions", "skill": name},
                "{% include skill-page.html skill=page.skill %}", written)
    removed = 0
    for folder in ("salaries", "cities", "skills"):
        for f in (ROOT / "data" / folder).glob("*.html"):
            if f not in written and MARK in f.read_text():
                f.unlink(); removed += 1
    print(f"{len(written)} stub pages written, {removed} stale removed")


if __name__ == "__main__":
    sys.exit(main())
